import streamlit as st  # Streamlit 기능을 st라는 짧은 이름으로 가져옵니다.


st.title("나의 자기소개 앱")  # 앱 화면의 가장 큰 제목을 표시합니다.

name = st.text_input("이름을 입력하세요")  # 입력한 이름을 name 변수에 저장합니다.

interest = st.selectbox(  # 여러 관심 분야 중 하나를 선택하는 입력창을 만듭니다.
    "관심 분야를 선택하세요",  # 선택 입력창 위에 표시할 안내 문구입니다.
    ["웹 개발", "인공지능", "데이터 분석", "게임 개발"],  # 사용자가 선택할 수 있는 항목입니다.
    index=None,  # 처음 화면에서는 아무 항목도 선택되지 않도록 설정합니다.
)

introduction = st.text_area(  # 여러 줄의 자기소개를 입력할 수 있는 입력창을 만듭니다.
    "자기소개를 입력하세요",  # 자기소개 입력창 위에 표시할 안내 문구입니다.
    placeholder="예: 새로운 기술을 배우는 것을 좋아합니다.",  # 입력 전에 보여 줄 예시 문장입니다.
)

st.divider()  # 입력 영역과 결과 영역 사이에 구분선을 표시합니다.

if name and interest and introduction:  # 이름, 관심 분야, 자기소개가 모두 입력되었는지 확인합니다.
    st.success("자기소개가 완성되었습니다!")  # 모든 입력이 완료되었다는 성공 메시지를 표시합니다.
    st.info(  # 입력한 내용을 하나의 정보 안내창에 넣어 자기소개 카드처럼 표시합니다.
        f"이름: {name}\n\n관심 분야: {interest}\n\n자기소개: {introduction}"  # 세 입력값을 카드에 함께 표시합니다.
    )
else:  # 세 입력값 중 하나라도 비어 있을 때 실행합니다.
    st.warning("모든 항목을 입력해 주세요.")  # 아직 입력하지 않은 항목이 있다는 안내 메시지를 표시합니다.
